#!/usr/bin/env python3
"""Decide GCC 15.2's answer to every __has_builtin query the headers make,
from GCC's own tables: cp-trait.def, the c_common_reswords keyword table,
the manual's builtin index (generic or AArch64 pages only) and the manual's
library-builtin list.  Writes a header for the GCC-identity preprocessing
runs and a JSON record of each decision and its basis.

usage: gccanswers.py OUTDIR CP_TRAIT_DEF C_COMMON_CC BUILTINS_DEF CP_DECL_CC OUT_H OUT_JSON
"""
import json
import re
import sys

TARGET_PAGES_OK = {"AArch64-Built_002din-Functions.html", "Other-Builtins.html",
                   "Bit-Operation-Builtins.html", "Byte_002dSwapping-Builtins.html",
                   "Integer-Overflow-Builtins.html", "Library-Builtins.html",
                   "Numeric-Builtins.html", "Object-Size-Checking.html",
                   "_005f_005fatomic-Builtins.html", "_005f_005fsync-Builtins.html",
                   "Type-Traits.html", "New_002fDelete-Builtins.html", "CRC-Builtins.html",
                   "Floating_002dPoint-Format-Builtins.html", "Return-Address.html",
                   "Stack-Allocation.html", "Vector-Extensions.html", "Offsetof.html",
                   "Other-Built_002din-Functions.html", "Built_002din-Functions.html"}


def main():
    out, trait_p, cc_p, bdef_p, cpdecl_p, out_h, out_j = sys.argv[1:8]
    steer = json.load(open(out + "/steer.json"))
    man = json.load(open(out + "/manindex.json"))
    traits = set(re.findall(r'^DEFTRAIT_\w+\s*\(\s*\w+\s*,\s*"([^"]+)"', open(trait_p).read(), re.M))
    cc = open(cc_p).read()
    rw = cc[cc.find("c_common_reswords[] ="):]
    rw = rw[:rw.find("\n};")]
    reswords = set(re.findall(r'\{ "([^"]+)"', rw))
    libfns = set(man["library_functions"])
    bdef = set()
    for m in re.finditer(r'^DEF_(\w+)\s*\(\s*BUILT_IN_\w+\s*,\s*"([^"]+)"', open(bdef_p).read(), re.M):
        nm = m.group(2)
        bdef.add("__builtin_" + nm)  # DEF_*_BUILTIN wrappers pass "__builtin_" NAME
        if "FLOATN" in m.group(1):
            for suf in ("f16", "f32", "f64", "f128", "f32x", "f64x", "f128x"):
                bdef.add("__builtin_" + nm.replace("__builtin_", "") + suf)
    cpdecl = set(re.findall(r'add_builtin_function\s*\(\s*"([^"]+)"', open(cpdecl_p).read()))
    decisions = {}
    names = set()
    for q in steer["queries"]:
        op, arg = q.split("(", 1)
        arg = arg[:-1].strip()
        if op in ("__has_builtin", "_GLIBCXX_HAS_BUILTIN", "_GLIBCXX_USE_BUILTIN_TRAIT",
                  "__glibc_has_builtin"):
            names.add(arg)
    for n in sorted(names):
        basis = []
        if n in traits:
            basis.append("cp-trait.def")
        if n in reswords:
            basis.append("c_common_reswords")
        if n in bdef:
            basis.append("builtins.def")
        if n in cpdecl:
            basis.append("cp/decl.cc")
        pages = [e["page"] for e in man["builtin"].get(n, [])]
        okp = [p for p in pages if p.split("/")[-1] in TARGET_PAGES_OK]
        if okp:
            basis.append("manual:" + okp[0].split("/")[-1])
        elif pages:
            basis.append("manual-target-only:" + pages[0].split("/")[-1])
        if n.startswith("__builtin_") and n[len("__builtin_"):] in libfns:
            basis.append("manual:Library-Builtins.html (%s)" % n[len("__builtin_"):])
        m = re.match(r"__builtin_(nans?|inf|huge_val|fabs|copysign)f(16|32|64|128|32x|64x)$", n)
        if m:
            basis.append("manual: _FloatN variant of __builtin_%s (n=%s)" % (m.group(1), m.group(2)))
        yes = any(not b.startswith("manual-target-only") for b in basis)
        decisions[n] = {"gcc": 1 if yes else 0, "basis": basis or ["not found in any GCC table"]}
    with open(out_h, "w") as f:
        f.write("/* GCC 15.2 answers to the __has_builtin queries made by the host headers\n"
                "   (generated by gccanswers.py; see host-header-extensions.md). */\n")
        for n, d in decisions.items():
            if d["gcc"]:
                f.write("#define __forge_hb_%s 1\n" % n)
        f.write("#undef __has_builtin\n#define __has_builtin(x) __forge_hb_##x\n")
    with open(out_j, "w") as f:
        json.dump(decisions, f, indent=1)
    for n, d in decisions.items():
        print("%d %-50s %s" % (d["gcc"], n, "; ".join(d["basis"])))


if __name__ == "__main__":
    main()
